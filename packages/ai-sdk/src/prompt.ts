import type {
  LanguageModelV4Content,
  LanguageModelV4Prompt,
} from "@ai-sdk/provider";

/**
 * Extracts text from the latest user message in a LanguageModelV4Prompt.
 */
export function extractLatestUserText(prompt: LanguageModelV4Prompt): string {
  for (let i = prompt.length - 1; i >= 0; i -= 1) {
    const message = prompt[i];
    if (message.role !== "user") {
      continue;
    }
    const chunks: string[] = [];
    for (const part of message.content) {
      if (part.type === "text" && part.text) {
        chunks.push(part.text);
      }
    }
    return chunks.join("\n").trim();
  }
  return "";
}

/**
 * Concatenates all text parts generated by a LanguageModelV4 doGenerate call.
 */
export function extractGeneratedText(
  content: readonly LanguageModelV4Content[],
): string {
  const chunks: string[] = [];
  for (const part of content) {
    if (part.type === "text" && part.text) {
      chunks.push(part.text);
    }
  }
  return chunks.join("");
}

/**
 * Immutably injects framed untrusted memory context into a LanguageModelV4Prompt.
 */
export function injectUntrustedMemoryContext(
  prompt: LanguageModelV4Prompt,
  framedContext: string,
  position: "system" | "user" = "system",
): LanguageModelV4Prompt {
  if (!framedContext.trim()) {
    return prompt;
  }

  if (position === "user") {
    for (let i = prompt.length - 1; i >= 0; i -= 1) {
      const msg = prompt[i];
      if (msg.role === "user") {
        const nextPrompt = [...prompt];
        nextPrompt[i] = {
          ...msg,
          content: [{ type: "text", text: `${framedContext}\n\n` }, ...msg.content],
        };
        return nextPrompt;
      }
    }
  }

  const sysIdx = prompt.findIndex((msg) => msg.role === "system");
  if (sysIdx >= 0) {
    const existing = prompt[sysIdx];
    if (existing.role === "system") {
      const nextPrompt = [...prompt];
      nextPrompt[sysIdx] = {
        ...existing,
        content: existing.content
          ? `${existing.content}\n\n${framedContext}`
          : framedContext,
      };
      return nextPrompt;
    }
  }

  return [{ role: "system", content: framedContext }, ...prompt];
}
